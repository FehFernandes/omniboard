#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// gen-resource — CRUD resource generator (following the Item pattern).
//
// Generates model + handlers (ALREADY scoped through scoped(c)) + a versioned
// migration + an integration test, and registers the resource at the right
// places (AutoMigrate, indexes/full-text and routes) through "// gen:*" anchors.
//
// Philosophy: generate-and-own. The output is the SAME boring code you would
// write by copying Item by hand — 100% editable, with no runtime abstraction.
// The gain is not forgetting a step (especially scoped(c), which is security).
//
// Usage (inside the Go app, where this script lives in tools/):
//   node tools/gen-resource.mjs --name Product
//   node tools/gen-resource.mjs --name Product --mode multitenant --app .
//
// --mode is autodetected (single vs multitenant) from the presence of
// internal/database/scope.go; pass --mode to force it.
// ═══════════════════════════════════════════════════════════════════════════

