// ── args ────────────────────────────────────────────────────────────────────
function parseArgs(argv) {
  const a = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) {
      const k = argv[i].slice(2), n = argv[i + 1];
      if (n && !n.startsWith('--')) { a[k] = n; i++; } else a[k] = true;
    }
  }
  return a;
}
function die(m) { console.error(`\n❌ ${m}\n`); process.exit(1); }

// ── naming ──────────────────────────────────────────────────────────────────
function tokens(s) { return String(s).replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^a-zA-Z0-9]+/).filter(Boolean); }
function pascal(s) { return tokens(s).map(t => t.charAt(0).toUpperCase() + t.slice(1)).join(''); }
function lowerFirst(s) { return s.charAt(0).toLowerCase() + s.slice(1); }
function snake(s) { return tokens(s).map(t => t.toLowerCase()).join('_'); }
function kebab(s) { return tokens(s).map(t => t.toLowerCase()).join('-'); }
function pluralize(w) {
  if (/(s|x|z|ch|sh)$/.test(w)) return w + 'es';
  if (/[^aeiou]y$/.test(w)) return w.slice(0, -1) + 'ies';
  return w + 's';
}

// ── insert a block before the anchor line, inheriting its indentation ───────
function insertBeforeAnchor(text, anchor, block) {
  const lines = text.split('\n');
  const idx = lines.findIndex(l => l.includes(anchor));
  if (idx === -1) return null;
  const indent = (lines[idx].match(/^\s*/) || [''])[0];
  const blockLines = block.split('\n').map(l => (l.length ? indent + l : l));
  lines.splice(idx, 0, ...blockLines);
  return lines.join('\n');
}

