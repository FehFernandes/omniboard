package models

import "time"

// BoardShare — public read-only link to ONE board of the workspace.
//
// Why a table and not a field in the workspace: the link needs to be revocable
// and auditable independently, and the lookup is by token (its own index). The
// content is NOT copied here — the public endpoint reads the owner's workspace
// and extracts only the shared document, so the link follows the edits and
// never exposes the other boards.
type BoardShare struct {
	BaseModel

	// Owner of the board. Every protected access is filtered by this.
	UserID string `gorm:"type:uuid;index;not null" json:"user_id"`

	// Id of the document inside the workspace (nanoid generated by BoardManager),
	// not a UUID from this database.
	BoardID string `gorm:"type:varchar(64);index;not null" json:"board_id"`

	// Name of the board at the moment the link was created. It makes the user's
	// list of links make sense even if the board is renamed later.
	BoardName string `gorm:"type:varchar(200)" json:"board_name"`

	// Opaque token of the public URL. Unique and indexed: it is the read key.
	Token string `gorm:"type:varchar(64);uniqueIndex;not null" json:"token"`

	// Revoked at. We do not delete the row: keeping the record prevents a revoked
	// token from being drawn again and preserves the trail of what was exposed.
	RevokedAt *time.Time `json:"revoked_at,omitempty"`

	// Access counters, useful for the owner to know whether the link circulated.
	Views      int64      `gorm:"not null;default:0" json:"views"`
	LastViewAt *time.Time `json:"last_view_at,omitempty"`
}

func (BoardShare) TableName() string { return "board_shares" }

// Ativo reports that the link still responds.
func (s BoardShare) Ativo() bool { return s.RevokedAt == nil }
